from PIL import Image, ImageDraw, ImageFont
import os


# ============================================================
# 广播 Title 样式
# ============================================================

# Title 主体尺寸
CARD_W = 300
CARD_H = 87

# 右侧向外伸出的竖条宽度
ACC_W = 10

# 右侧竖条高度
ACC_H = 45

# 顶部蓝色标题栏高度
BAR_H = 45

# 主体描边宽度
BORDER = 3


# ============================================================
# 布局偏移
# ============================================================

# 项目名称水平偏移量
#
#   0     = 默认位置
#   -10   = 向左移动 10px
#   -20   = 向左移动 20px
#   +10   = 向右移动 10px
#
# 注意：
# 这里填写的是最终图片尺寸下的逻辑像素。
# 绘制时会自动乘以超采样倍率 s。
#
PROG_OFFSET_X = -25


# ============================================================
# 固定颜色
#
# 注意：
# 顶部矩形和右侧竖条的颜色是固定的。
# 切换“正在 / 即将”状态时，
# 这两个颜色都不会发生变化。
# ============================================================

# 下半部分浅灰色背景
BG = (218, 224, 229)

# 主体和蓝条的浅色描边
EDGE = (242, 245, 247)

# 白色文字
WHITE = (255, 255, 255)

# 黑色文字
BLACK = (20, 20, 20)


# ============================================================
# 固定的顶部蓝色
#
# 无论当前是：
#
#     正在
#     即将
#
# 顶部矩形始终使用这一个颜色。
# ============================================================

BAR_COLOR = (0, 84, 183)

# 右侧竖条也保持固定，不随状态改变
ACC_COLOR = (0, 70, 165)


# ============================================================
# 两种状态
#
# 这里只控制底部 Chip。
#
# 每一个状态包含：
#
#   1. 状态完整名称
#   2. Chip 显示文字
#   3. Chip 颜色
#
# 注意：
# 已经删除“等待”状态。
# ============================================================

STATES = [
    (
        "正在播送",
        "正在播送",
        (72, 196, 160),     # Chip：绿色
    ),

    (
        "即将播送",
        "即将播送",
        (220, 55, 55),      # Chip：红色
    ),
]


# ============================================================
# 文本
# ============================================================

EVENT = "绵阳中学运动会"
PROG = "20×50接力"


# ============================================================
# 字体
# ============================================================

def font(sz, bold=False):
    """
    加载微软雅黑字体。

    Windows 下优先使用：

        msyh.ttc      普通
        msyhbd.ttc    粗体

    如果不存在，则尝试使用黑体。
    """

    paths = (
        r"C:\Windows\Fonts\msyhbd.ttc"
        if bold
        else r"C:\Windows\Fonts\msyh.ttc",

        r"C:\Windows\Fonts\simhei.ttf",
    )

    for p in paths:
        if os.path.exists(p):
            try:
                return ImageFont.truetype(
                    p,
                    int(sz)
                )
            except Exception:
                pass

    # 最后的 fallback
    return ImageFont.load_default()


# ============================================================
# 根据可用宽度自动计算字体大小
# ============================================================

def fit_font_size(
    text,
    max_width,
    max_size,
    min_size=8,
    bold=True
):
    """
    根据文字实际像素宽度自动寻找合适字号。

    max_width：
        允许文字占用的最大宽度。

    max_size：
        最大字号。

    min_size：
        最小字号。

    这样可以避免标题或项目名称过长时溢出。
    """

    if not text:
        return int(min_size)

    size = int(max_size)

    while size >= min_size:

        f = font(
            size,
            bold
        )

        box = f.getbbox(text)

        width = box[2] - box[0]

        if width <= max_width:
            return size

        size -= 1

    return int(min_size)


# ============================================================
# 居中文字
# ============================================================

def draw_center_text(
    draw,
    box,
    text,
    fnt,
    fill
):
    """
    在指定矩形区域内让文字真正居中。

    box：

        (x1, y1, x2, y2)

    使用 textbbox 计算字体实际边界，
    避免中文字体上下偏移导致视觉上不居中。
    """

    x1, y1, x2, y2 = box

    tb = draw.textbbox(
        (0, 0),
        text,
        font=fnt
    )

    tw = tb[2] - tb[0]
    th = tb[3] - tb[1]

    x = (
        x1
        + (x2 - x1 - tw) / 2
        - tb[0]
    )

    y = (
        y1
        + (y2 - y1 - th) / 2
        - tb[1]
    )

    draw.text(
        (x, y),
        text,
        font=fnt,
        fill=fill,
    )


# ============================================================
# 绘制单个 Title
# ============================================================

def card(
    state_name,
    chip_text,
    chip_c,
    s=2.0,
):
    """
    绘制一个完整的广播 Title。

    参数：

        state_name
            状态完整名称。
            例如：
                正在播送
                即将播送

            这里只用于保持数据结构清晰，
            实际绘制时不参与颜色判断。

        chip_text
            底部状态色块中的文字。

        chip_c
            底部状态色块颜色。

        s
            超采样倍率。

    ========================================================

    最终逻辑尺寸：

        CARD_W × CARD_H
        300 × 87

    实际绘制：

        600 × 174

    最后再缩小到最终尺寸，
    让文字和边缘更加平滑。
    """

    # ========================================================
    # 1. 根据超采样倍率计算实际绘制尺寸
    # ========================================================

    cw = int(CARD_W * s)
    ch = int(CARD_H * s)

    # 右侧竖条会超出主体宽度
    total_w = int(
        (CARD_W + ACC_W) * s
    )

    # 创建画布
    img = Image.new(
        "RGB",
        (total_w, ch),
        (28, 32, 38),
    )

    d = ImageDraw.Draw(img)


    # ========================================================
    # 2. 灰色主体
    # ========================================================

    d.rectangle(
        [
            0,
            0,
            cw - 30,
            ch - 1,
        ],
        fill=BG,
    )


    # ========================================================
    # 3. 主体外框
    # ========================================================

    d.rectangle(
        [
            0,
            0,
            cw - 24,
            ch - 1,
        ],
        outline=EDGE,
        width=max(
            1,
            int(BORDER * s)
        ),
    )


    # ========================================================
    # 4. 顶部蓝色标题栏
    #
    # 这里使用固定的 BAR_COLOR。
    #
    # 不管当前是“正在”还是“即将”，
    # 顶部矩形颜色都不会改变。
    # ========================================================

    bar_w = (
        cw
        - int(ACC_W * s)
        - int(2 * s)
    )

    d.rectangle(
        [
            0,
            0,
            bar_w,
            int(BAR_H * s),
        ],
        fill=BAR_COLOR,
        outline=EDGE,
        width=max(
            1,
            int(BORDER * s)
        ),
    )


    # ========================================================
    # 5. 右侧竖条
    #
    # 同样使用固定的 ACC_COLOR。
    #
    # 切台时不会改变。
    # ========================================================

    ax = cw - int(ACC_W * s)

    d.rectangle(
        [
            ax - 3,
            0,
            total_w - 1,
            int(ACC_H * s),
        ],
        fill=ACC_COLOR,
    )


    # ========================================================
    # 6. 顶部标题文字
    #
    # 例如：
    #
    #        绵阳中学运动会
    #
    # ========================================================

    event_max_width = bar_w * 0.82

    event_size = fit_font_size(
        EVENT,
        event_max_width,
        max_size=23 * s,
        min_size=12 * s,
        bold=True,
    )

    event_font = font(
        event_size,
        True
    )

    draw_center_text(
        d,
        (
            0,
            0,
            bar_w,
            int(BAR_H * s),
        ),
        EVENT,
        event_font,
        WHITE,
    )


    # ========================================================
    # 7. 计算底部内容区域
    # ========================================================

    body_top = int(BAR_H * s)
    body_bottom = ch

    body_h = body_bottom - body_top


    # ========================================================
    # 8. 计算 Chip 字体和宽度
    #
    # Chip 只负责显示：
    #
    #     正在播送
    #     即将播送
    #
    # ========================================================

    chip_preview_font = font(
        int(14 * s),
        True
    )

    chip_box = d.textbbox(
        (0, 0),
        chip_text,
        font=chip_preview_font,
    )

    chip_text_w = (
        chip_box[2]
        - chip_box[0]
    )

    # Chip 左右留白
    chip_pad_x = int(7 * s)

    # Chip 总宽度
    chip_w = (
        chip_text_w
        + chip_pad_x * 2
    )


    # ========================================================
    # 9. Chip 和项目名称之间的间距
    # ========================================================

    chip_gap = int(6 * s)


    # ========================================================
    # 10. 计算项目名称可以使用的宽度
    # ========================================================

    prog_max_width = (
        cw
        - chip_w
        - chip_gap
        - int(8 * s)
    )

    prog_max_width = max(
        prog_max_width,
        int(40 * s)
    )


    # ========================================================
    # 11. 项目名称字体
    # ========================================================

    prog_size = fit_font_size(
        PROG,
        prog_max_width,
        max_size=19 * s,
        min_size=10 * s,
        bold=True,
    )

    prog_font = font(
        prog_size,
        True
    )


    # ========================================================
    # 12. 计算底部文字行高度
    # ========================================================

    prog_box = d.textbbox(
        (0, 0),
        PROG,
        font=prog_font,
    )

    prog_text_h = (
        prog_box[3]
        - prog_box[1]
    )

    # Chip 和项目名称统一使用这个高度
    row_h = int(body_h * 0.9)

    # 底部内容整体垂直居中
    row_y = (
        body_top
        + (body_h - row_h) / 2
        - 2
    )


    # ========================================================
    # 13. 绘制底部状态 Chip
    #
    # 这是唯一会随状态改变颜色的矩形。
    #
    # 正在：
    #
    #   ┌────────┐
    #   │ 正在播送 │
    #   └────────┘
    #
    # 即将：
    #
    #   ┌────────┐
    #   │ 即将播送 │
    #   └────────┘
    #
    # Chip 自身的位置不受项目名称偏移影响。
    # ========================================================

    chip_x1 = 7
    chip_y1 = int(row_y)

    chip_x2 = (
        chip_x1
        + chip_w
    )

    chip_y2 = (
        chip_y1
        + row_h
    )

    d.rectangle(
        [
            chip_x1,
            chip_y1,
            chip_x2,
            chip_y2,
        ],
        fill=chip_c,
    )


    # ========================================================
    # 14. Chip 文字
    #
    # Chip 使用白色粗体。
    # ========================================================

    chip_font_size = int(
        row_h * 0.4
    )

    chip_font_size = max(
        chip_font_size,
        int(8 * s)
    )

    chip_font = font(
        chip_font_size,
        True
    )

    draw_center_text(
        d,
        (
            chip_x1,
            chip_y1,
            chip_x2,
            chip_y2,
        ),
        chip_text,
        chip_font,
        WHITE,
    )


    # ========================================================
    # 15. 绘制项目名称
    #
    # 项目名称始终使用黑色。
    #
    # --------------------------------------------------------
    # 项目名称水平偏移
    #
    # PROG_OFFSET_X：
    #
    #     0       默认位置
    #     -10     向左移动 10px
    #     -20     向左移动 20px
    #     +10     向右移动 10px
    #
    # 这里同时移动 prog_left 和 prog_right，
    # 所以项目名称会作为一个整体进行平移，
    # 不会改变文字在区域内部的居中方式。
    # ========================================================

    prog_offset_x = PROG_OFFSET_X * s

    prog_left = (
        chip_x2
        + chip_gap
        + prog_offset_x
    )

    prog_right = (
        cw
        + prog_offset_x
    )

    draw_center_text(
        d,
        (
            prog_left,
            int(row_y),
            prog_right,
            int(row_y + row_h),
        ),
        PROG,
        prog_font,
        BLACK,
    )


    # ========================================================
    # 16. 返回绘制结果
    # ========================================================

    return img


# ============================================================
# 主预览
# ============================================================

def main():

    # ========================================================
    # 超采样倍率
    # ========================================================

    s = 2.0


    # ========================================================
    # 预览布局
    # ========================================================

    margin = 32

    # 左侧状态名称区域宽度
    label_w = 130

    # 两个 Title 之间的垂直间距
    gap = 20


    # ========================================================
    # 生成两个状态
    #
    # 注意现在只有两个状态：
    #
    #     正在播送
    #     即将播送
    #
    # ========================================================

    cards = [
        card(
            state_name,
            chip_text,
            chip_c,
            s=s,
        )
        for (
            state_name,
            chip_text,
            chip_c
        ) in STATES
    ]


    # ========================================================
    # 获取单个卡片尺寸
    # ========================================================

    cw, ch = cards[0].size


    # ========================================================
    # 创建最终预览图
    # ========================================================

    out_w = (
        label_w
        + cw
        + margin * 2
    )

    # 现在只有两个状态
    out_h = (
        margin
        + 40
        + ch * 2
        + gap
        + margin
    )

    out = Image.new(
        "RGB",
        (out_w, out_h),
        (28, 32, 38),
    )

    od = ImageDraw.Draw(out)


    # ========================================================
    # 预览标题
    # ========================================================

    od.text(
        (margin, 8),
        "解说端 Title · 两态对照",
        font=font(24, True),
        fill=(220, 220, 220),
    )


    # 第一个卡片的 Y 坐标
    y = margin + 40


    # 左侧状态名称字体
    nf = font(
        20,
        True
    )


    # ========================================================
    # 逐个绘制两个状态
    # ========================================================

    for (
        state,
        img
    ) in zip(
        STATES,
        cards
    ):

        # STATES 当前结构：
        #
        # (
        #     "正在播送",
        #     "正在播送",
        #     chip_color
        # )
        #
        # state[0]：
        #     左侧完整状态名称。

        name = state[0]


        # ====================================================
        # 粘贴 Title
        # ====================================================

        out.paste(
            img,
            (
                label_w + margin,
                y,
            ),
        )


        # ====================================================
        # 左侧状态名称
        #
        # 正在播送
        # 即将播送
        # ====================================================

        nt = od.textbbox(
            (0, 0),
            name,
            font=nf,
        )

        nh = nt[3] - nt[1]

        od.text(
            (
                margin,
                y
                + (ch - nh) / 2
                - nt[1],
            ),
            name,
            font=nf,
            fill=(190, 190, 190),
        )


        # 下一个 Title
        y += ch + gap


    # ============================================================
    # 输出 PNG
    # ============================================================

    output = os.path.join(
        os.path.dirname(__file__),
        "title-preview.png",
    )

    out.save(
        output,
        "PNG",
    )


    print(
        "saved",
        output,
        out.size,
    )


# ============================================================
# 程序入口
# ============================================================

if __name__ == "__main__":
    main()